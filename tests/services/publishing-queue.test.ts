import assert from 'node:assert/strict';
import {test} from 'node:test';
import {PublishingService} from '../../apps/api/src/modules/publishing/publishing.service.ts';
import {BatchStatusService} from '../../apps/api/src/modules/publishing/batch-status.service.ts';
import {PublisherRegistry} from '../../apps/api/src/modules/publishing/publisher-registry.ts';
import {StrategyResolver} from '../../apps/api/src/modules/publishing/strategy-resolver.ts';
import {FakePublisher} from '../../apps/worker/src/testing/fake-publisher.ts';
import {MemoryRepositories} from '../../packages/shared/src/memory-repositories.ts';
import {MemoryStore} from '../../packages/shared/src/store.ts';
import {InMemoryJobQueue} from '../../packages/shared/src/job-queue.ts';

test('publishing schedules jobs and calendar reschedule/cancel updates the queue', async () => {
  const repos = new MemoryRepositories(new MemoryStore());
  await repos.workspaces.insert({id: 'w', name: 'Workspace'});
  await repos.brands.insert({id: 'b', workspaceId: 'w', name: 'Brand', slug: 'brand', language: 'vi', timezone: 'Asia/Bangkok', currency: 'VND', status: 'ACTIVE'});
  await repos.contents.insert({id: 'c', brandId: 'b', type: 'TEXT', title: 'Post', body: 'Hello', status: 'READY'});
  await repos.variants.insert({id: 'v', contentItemId: 'c', platform: 'FACEBOOK', hashtags: [], status: 'READY'});
  await repos.socialAccounts.insert({id: 'a', brandId: 'b', platform: 'FACEBOOK', publishMode: 'API', status: 'CONNECTED'});
  const registry = new PublisherRegistry();
  registry.register('FACEBOOK', 'API', new FakePublisher());
  let now = 0;
  const delivered: string[] = [];
  const queue = new InMemoryJobQueue(async id => {delivered.push(id)}, () => now);
  const publishing = new PublishingService(repos, registry, new StrategyResolver(), queue);
  const status = new BatchStatusService(repos, undefined, queue);
  const first = await publishing.createBatch({brandId: 'b', contentId: 'c', createdBy: 'owner', socialAccountIds: ['a'], scheduledAt: 1000});
  const firstId = first.results[0]?.jobId;
  assert.ok(firstId);
  const duplicate = await publishing.createBatch({brandId: 'b', contentId: 'c', createdBy: 'owner', socialAccountIds: ['a'], scheduledAt: 1000});
  assert.equal(duplicate.batchId, first.batchId);
  assert.equal(duplicate.results[0]?.jobId, firstId);
  assert.equal((await repos.publishJobs.findBy({batchId: first.batchId})).length, 1);
  assert.equal((await repos.publishBatches.findBy({brandId: 'b'})).length, 1);
  await status.reschedule(firstId, 2000);
  now = 1000;
  await queue.tick();
  assert.deepEqual(delivered, []);
  now = 2000;
  await queue.tick();
  assert.deepEqual(delivered, [firstId]);
  const second = await publishing.createBatch({brandId: 'b', contentId: 'c', createdBy: 'owner', socialAccountIds: ['a'], scheduledAt: 3000});
  const secondId = second.results[0]?.jobId;
  assert.ok(secondId);
  await status.cancel(secondId);
  now = 3000;
  await queue.tick();
  assert.deepEqual(delivered, [firstId]);
  await queue.close();
});
